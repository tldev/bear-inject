/**
 * Compiles ./snippets/{head,nav,top,bottom,body}/*.html from the consumer's
 * repo (the current directory) into .bear-inject/snippets.generated.js, plus
 * a Worker entry module that wires them into createWorker.
 *
 * Workers cannot read files at runtime, so snippet HTML is baked into the
 * bundle. Files inject in filename order (hence the NN- prefixes), and
 * anything not ending in .html (e.g. *.html.example) is ignored. {{VAR}}
 * placeholders are substituted from the Worker's vars at request time; see
 * src/inject.js.
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const outDir = join(root, ".bear-inject");
const snippets = [];

// Must match PLACEMENTS in src/inject.js; order here fixes the injection
// (and x-injected-snippets) order across placements.
for (const placement of ["head", "nav", "top", "bottom", "body"]) {
  let files = [];
  try {
    files = readdirSync(join(root, "snippets", placement))
      .filter((f) => f.endsWith(".html"))
      .sort();
  } catch {
    continue; // a placement directory is allowed to not exist
  }
  for (const f of files) {
    const html = readFileSync(join(root, "snippets", placement, f), "utf8").trim();
    const vars = [
      ...new Set([...html.matchAll(/\{\{\s*([A-Z][A-Z0-9_]*)\s*\}\}/g)].map((m) => m[1])),
    ];
    snippets.push({ name: f.replace(/\.html$/, ""), placement, html, vars });
  }
}

// Names must be unique across placement directories: they key the
// x-injected-snippets header, and live verification counts each snippet's
// occurrences, so file contents should be distinct too.
const dupes = snippets.map((s) => s.name).filter((n, i, a) => a.indexOf(n) !== i);
if (dupes.length) {
  console.error(`duplicate snippet name(s) across placements: ${[...new Set(dupes)].join(", ")}`);
  process.exit(2);
}

mkdirSync(outDir, { recursive: true });

writeFileSync(
  join(outDir, "snippets.generated.js"),
  `// Generated by bear-inject gen. Do not edit; edit snippets/ instead.
export default ${JSON.stringify(
    snippets.map(({ name, placement, html }) => ({ name, placement, html })),
    null,
    2,
  )};
`,
);

writeFileSync(
  join(outDir, "entry.js"),
  `// Generated by bear-inject gen. Do not edit.
import { createWorker } from "bear-inject";
import SNIPPETS from "./snippets.generated.js";
export default createWorker(SNIPPETS);
`,
);

console.log(`snippets: compiled ${snippets.length}`);
for (const s of snippets) {
  console.log(`  ${s.placement}/${s.name}${s.vars.length ? `  (needs ${s.vars.join(", ")})` : ""}`);
}
